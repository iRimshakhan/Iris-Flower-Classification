import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

#Load the data
df = pd.read_csv("/content/iris_dataset.csv")
df.head()

df.info()

df.describe()

df.species.value_counts()

#finding null values
df.isnull().sum()

#finding outliers

sns.boxplot(df)

sns.boxplot(df.sepal_width_cm)

#Treatment of Outlier
Q1 = df['sepal_width_cm'].quantile(0.25)
Q3 = df['sepal_width_cm'].quantile(0.75)
IQR = Q3-Q1
lower_limit = Q1 - 1.5*IQR
upper_limit = Q3 + 1.5*IQR
df['sepal_width_cm'] = np.where(df['sepal_width_cm']>upper_limit, upper_limit, df['sepal_width_cm'])
df['sepal_width_cm'] = np.where(df['sepal_width_cm']<lower_limit, lower_limit, df['sepal_width_cm'])
sns.boxplot(df)

plt.figure(figsize=(8, 5))
sns.scatterplot(
    data=df,
    x="petal_length_cm",
    y="petal_width_cm",
    hue="species",
    s=70
)
plt.title("Petal Length vs Petal Width by Species")
plt.tight_layout()
plt.show()

plt.figure(figsize=(8, 5))
sns.scatterplot(
    data=df,
    x="sepal_length_cm",
    y="sepal_width_cm",
    hue="species",
    s=70
)
plt.title("Sepal Length vs Sepal Width by Species")
plt.tight_layout()
plt.show()

df["species"].value_counts().plot.pie(
    autopct="%1.1f%%",
    figsize=(6, 6)
)
plt.title("Species Distribution")
plt.ylabel("")
plt.show()

#Lable Encoding - object to numbers

from sklearn.preprocessing import LabelEncoder

le = LabelEncoder()
df['species'] = le.fit_transform(df['species'])
df.head()

#Split into training and testing data

from sklearn.model_selection import train_test_split

X = df.drop('species', axis = 1)
y = df[['species']]

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size = 0.20, random_state=42, stratify=y)

#Create the model

from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression

model = make_pipeline(
    StandardScaler(),
    LogisticRegression(max_iter=1000)
)

#Train the model
model.fit(X_train, y_train)

#Make predictions
y_pred = model.predict(X_test)

#Evaluate the model
from sklearn.metrics import accuracy_score, classification_report

print("Accuracy:", accuracy_score(y_test, y_pred))
print(classification_report(
    y_test, y_pred,
    target_names=le.classes_
))

# Confusion matrix
from sklearn.metrics import ConfusionMatrixDisplay

ConfusionMatrixDisplay.from_predictions(
    y_test,
    y_pred,
    labels=[0, 1, 2],
    display_labels=le.classes_,
    cmap="Blues"
)
plt.title("Logistic Regression - Confusion Matrix")
plt.tight_layout()
plt.show()

#Predict a new flower
new_flower = [[5.1, 3.5, 1.4, 0.2]]
prediction = model.predict(new_flower)[0]
probabilities = model.predict_proba(new_flower)[0]

print("Predicted flower:", le.classes_[prediction])

